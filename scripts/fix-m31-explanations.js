// 해설 보충 적용
data.lessons.forEach(lesson => {
  const nodeSupp = supplements[lesson.node_id];
  if (!nodeSupp) return;
  lesson.questions.forEach((q, qi) => {
    const supp = nodeSupp[qi];
    if (supp && q.explanation.length < 80) {
      q.explanation = q.explanation + ' ' + supp;
    }
  });
});

// answer_index 분산 조정 (options 순서도 함께 swap)
function swapOptions(q, i, j) {
  const tmpOpt = q.options[i];
  q.options[i] = q.options[j];
  q.options[j] = tmpOpt;
  if (q.answer_index === i) q.answer_index = j;
  else if (q.answer_index === j) q.answer_index = i;
}

const answerAdjust = {
  // [node_id]: [[qi, fromIdx, toIdx], ...]  — swap fromIdx<->toIdx in options
  'E4MATA03B02C07D02': [[0, 0, 2]],   // Q1: 정답을 idx2로(50→idx2)
  'E4MATA03B24C67D01': [[0, 1, 3]],   // Q1: idx1->idx3
  'E4MATA03B24C67D03': [[0, 1, 3],[1, 1, 3]], // Q1,Q2
  'E4MATA03B24C68D01': [[0, 1, 2]],
  'E4MATA03B25C69D01': [[0, 1, 4]],   // Q1: idx1->idx4
  'E4MATA03B25C70D02': [[0, 1, 3]],
  'E4MATA03B04C10D02': [[0, 0, 3]],
  'E4MATA03B04C11D01': [[0, 1, 4]],
  'E4MATA03B04C11D02': [[0, 1, 4],[2, 0, 3]],
  'E4MATA03B04C12D01': [[0, 2, 4]],
  'E4MATA03B05C13D01': [[0, 1, 4]],
};

data.lessons.forEach(lesson => {
  const adj = answerAdjust[lesson.node_id];
  if (!adj) return;
  adj.forEach(([qi, from, to]) => {
    swapOptions(lesson.questions[qi], from, to);
  });
});

